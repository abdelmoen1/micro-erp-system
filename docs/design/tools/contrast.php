<?php
// TC-1501-01: computes WCAG 2.x contrast for every pair in docs/design/tokens.json
// and writes docs/design/contrast-report.md. Exit code 1 if any pair fails.
// Usage: php docs/design/tools/contrast.php

$dir = dirname(__DIR__);
$tokens = json_decode(file_get_contents("$dir/tokens.json"), true, flags: JSON_THROW_ON_ERROR);

function luminance(string $hex): float
{
    $rgb = array_map(fn($c) => hexdec($c) / 255, str_split(ltrim($hex, '#'), 2));
    $lin = array_map(fn($c) => $c <= 0.04045 ? $c / 12.92 : (($c + 0.055) / 1.055) ** 2.4, $rgb);
    return 0.2126 * $lin[0] + 0.7152 * $lin[1] + 0.0722 * $lin[2];
}

function ratio(string $a, string $b): float
{
    [$hi, $lo] = [max(luminance($a), luminance($b)), min(luminance($a), luminance($b))];
    return ($hi + 0.05) / ($lo + 0.05);
}

$out = ["# Contrast report (TC-1501-01)", "",
    "> Generated by `php docs/design/tools/contrast.php` from [tokens.json](tokens.json). Do not edit by hand.", "",
    "Thresholds (WCAG 2.2 AA): text **4.5:1**; non-text UI parts (borders of inputs, focus ring) **3:1**.", ""];
$failures = 0;

foreach ($tokens['directions'] as $id => $direction) {
    $c = $direction['color'];
    $out[] = "## {$direction['name']}";
    $out[] = "";
    $out[] = "| Foreground | Background | Ratio | Needed | Result |";
    $out[] = "|---|---|---|---|---|";
    $rows = [];
    foreach ($tokens['contrastPairs'] as [$fg, $bg]) $rows[] = [$fg, $bg, 4.5];
    foreach ($tokens['nonTextPairs'] as [$fg, $bg]) $rows[] = [$fg, $bg, 3.0];
    foreach ($rows as [$fg, $bg, $need]) {
        $r = ratio($c[$fg], $c[$bg]);
        $ok = $r >= $need;
        $failures += $ok ? 0 : 1;
        $out[] = sprintf("| `%s` %s | `%s` %s | %.2f | %.1f | %s |", $fg, $c[$fg], $bg, $c[$bg], $r, $need, $ok ? 'pass' : '**FAIL**');
    }
    $out[] = "";
}

$out[] = $failures === 0 ? "**Result: all pairs pass.**" : "**Result: $failures pair(s) fail.**";
file_put_contents("$dir/contrast-report.md", implode("\n", $out) . "\n");
echo $failures === 0 ? "all pairs pass\n" : "$failures pair(s) fail\n";
exit($failures === 0 ? 0 : 1);
